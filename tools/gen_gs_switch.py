#!/usr/bin/env python3
# The GS-Z80's switch dispatch (external/redcode/Z80_redcode.c, GS_Z80_SWITCH): the case
# labels of z80_run's switch over the unprefixed opcodes, read from redcode's insn_table
# itself so the switch can never disagree with it. Re-run after editing the table.
#   usage: gen_gs_switch.py [policy]     (writes external/redcode/Z80_gs_switch.inc)
#
# Every case calls the table's handler, inlined (always_inline under GS_Z80_SWITCH).
# A case that holds ONE opcode sees it as a constant: the register-table lookups
# (J0 / K0 / SS0 / TT / Z(...)) and the ALU's operation switch fold away - but each such
# case is a copy of the body. Opcodes that share a handler are therefore grouped into one
# case (one copy, the lookups stay) unless the policy below splits them:
#   'op'  every opcode its own case;
#   'alu' one case per ALU operation (bits 5-3), the operand register stays a lookup;
#   'call' no inline copy: the case calls the handler's out-of-line copy (it exists
#         anyway for insn_table's other users: DD/FD + a plain opcode, IM 0, the hook);
#   absent = one inline case for all of the handler's opcodes.
# Size is SRAM: z80_run sits in the .gsovl window (heap on every GS boot).
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'external', 'redcode', 'Z80_redcode.c')
text = open(src).read()

def table(name):
    m = re.search(r'static Insn const ' + name + r'\s*\[256\]\s*=\s*\{(.*?)\};', text, re.S)
    if not m:
        sys.exit('table %s not found' % name)
    body = re.sub(r'/\*.*?\*/', '', m.group(1), flags=re.S)
    names = [t.strip() for t in body.split(',') if t.strip()]
    if len(names) != 256:
        sys.exit('table %s: %d entries' % (name, len(names)))
    return names

# The switch keeps the cycle count, R and PC in locals. GS_SWX: handlers that read or
# write self->cycles / R themselves, or call a table; all three are published around them.
# GS_SWP: a table call that needs only PC published (the CB handlers use self->pc).
SPECIAL = {'halt', 'dd_prefix', 'fd_prefix', 'ed_prefix', 'hook'}
PCONLY = {'cb_prefix'}

POLICIES = {
    'none': {},
    'all':  None,                      # every opcode its own case
    # 2026-11-20, from the card's opcode mix (host PICOSPECCY_GSMEM=1 [GSOPS], TheLink):
    # 95 % of the M1s unprefixed, JR NZ / OR A / IN A,(n) / LD A,(BC) / ADD HL,DE /
    # LD (DE),A / INC r / SUB n / POP / LD r,r' on top; the rare ones are calls.
    'gs':   {'ld_J_K': 'op', 'V_J': 'op', 'U_a_K': 'alu', 'U_a_vhl': 'op', 'U_a_BYTE': 'op',
             'jr_Z_OFFSET': 'op',
             'ld_J_BYTE': 'op', 'ld_J_vhl': 'op', 'ld_vhl_K': 'op',
             'inc_SS': 'op', 'dec_SS': 'op', 'add_hl_SS': 'op', 'ld_SS_WORD': 'op',
             'push_TT': 'op', 'pop_TT': 'op',
             'daa': 'call', 'cpl': 'call', 'scf': 'call', 'ccf': 'call', 'rlca': 'call',
             'rrca': 'call', 'rla': 'call', 'rra': 'call', 'rst_N': 'call', 'ex_vsp_hl': 'call',
             'di': 'call', 'ei': 'call', 'ld_sp_hl': 'call', 'V_vhl': 'call',
             'ld_vhl_BYTE': 'call', 'ld_a_vWORD': 'call', 'ld_vWORD_a': 'call',
             'ld_hl_vWORD': 'call', 'ld_vWORD_hl': 'call', 'ex_af_af_': 'call'},
    'hot':  {'ld_J_K': 'op', 'V_J': 'op', 'U_a_K': 'alu', 'U_a_vhl': 'op', 'U_a_BYTE': 'op',
             'jr_Z_OFFSET': 'op', 'ret_Z': 'op', 'jp_Z_WORD': 'op', 'call_Z_WORD': 'op',
             'ld_J_BYTE': 'op', 'ld_J_vhl': 'op', 'ld_vhl_K': 'op',
             'inc_SS': 'op', 'dec_SS': 'op', 'add_hl_SS': 'op', 'ld_SS_WORD': 'op',
             'push_TT': 'op', 'pop_TT': 'op'},
}
policy_name = sys.argv[1] if len(sys.argv) > 1 else 'gs'
policy = POLICIES[policy_name]

def how(n):
    return 'op' if policy is None else policy.get(n)

def key(n, op):
    h = how(n)
    if h == 'op':  return op
    if how == 'alu': return (op >> 3) & 7
    return None

names = table('insn_table')
groups = {}                            # (handler, key) -> opcodes, in first-opcode order
for op, n in enumerate(names):
    groups.setdefault((n, key(n, op)), []).append(op)
path = os.path.join(here, '..', 'external', 'redcode', 'Z80_gs_switch.inc')
with open(path, 'w') as f:
    f.write('/* Generated by tools/gen_gs_switch.py (policy "%s") from insn_table in Z80_redcode.c - do not edit. */\n' % policy_name)
    for (n, k), ops in groups.items():
        f.write('%s %s(%s)\n' % (' '.join('case 0x%02X:' % o for o in ops),
                                 'GS_SWX' if n in SPECIAL else
                                 'GS_SWP' if n in PCONLY or how(n) == 'call' else 'GS_SW', n))
print('Z80_gs_switch.inc: policy %s, %d cases, %d handlers' % (policy_name, len(groups), len(set(names))))
