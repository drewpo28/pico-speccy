def glyph_rows(ch):
    """Return the 10 row bitmaps of `ch` as ints (bit5 = x0)."""
    if ch not in G:
        raise KeyError("no art for %r (0x%02X)" % (ch, ord(ch)))
    top, art = G[ch]
    rows = [0] * H
    for i, line in enumerate(art):
        y = top + i
        if y >= H:
            raise ValueError("%r overflows the cell: row %d" % (ch, y))
        if len(line) > W:
            raise ValueError("%r row %d is %d px wide (max %d)" % (ch, y, len(line), W))
        bits = 0
        for x, c in enumerate(line):
            if c == '#':
                bits |= 1 << (W - 1 - x)
            elif c != '.':
                raise ValueError("%r row %d: bad char %r" % (ch, y, c))
        rows[y] = bits
    return rows


def preview():
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        rows = glyph_rows(ch)
        print("0x%02X '%s'" % (code, ch))
        for r in rows:
            print("   " + "".join('#' if r & (1 << (W - 1 - x)) else '.'
                                  for x in range(W)))
        print()


def emit(path):
    out = []
    out.append("// pico-speccy — 6x10 fixed-width UI font of the new OSD menu.")
    out.append("//")
    out.append("// GENERATED by tools/mkuifont.py — edit the glyph art there, not here.")
    out.append("//")
    out.append("// Cell 6x10 (5 px art + 1 px advance gap). One byte per row, bit 5 is the")
    out.append("// leftmost pixel. Baseline is row 7; rows 8..9 carry descenders.")
    out.append("// Deliberately not the ZX face: this UI has its own renderer and font.")
    out.append("")
    out.append('#include "UiFont.h"')
    out.append("")
    out.append("namespace nm {")
    out.append("")
    # Guard against UiFont.h's FIRST/LAST drifting away from this table.
    out.append("static_assert(UI_FONT_FIRST == 0x%02X && UI_FONT_LAST == 0x%02X," % (FIRST, LAST))
    out.append('              "UiFont.h bounds do not match tools/mkuifont.py");')
    out.append("")
    out.append("const uint8_t ui_font6x10[UI_FONT_COUNT * UI_FONT_H] = {")
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        rows = glyph_rows(ch)
        art = "".join('#' if rows[1] & (1 << (W - 1 - x)) else '.' for x in range(W))
        label = ch if ch != '\\' else '\\\\'
        out.append("    %s // 0x%02X '%s'" % (
            "".join("0x%02X," % r for r in rows), code, label))
    out.append("};")
    out.append("")
    out.append("} // namespace nm")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote %s (%d glyphs, %d bytes of flash)"
          % (path, LAST - FIRST + 1, (LAST - FIRST + 1) * H))


if __name__ == "__main__":
    # Fail loudly if a printable ASCII glyph is missing.
    missing = [chr(c) for c in range(FIRST, LAST + 1) if chr(c) not in G]
    if missing:
        sys.exit("missing glyph art for: %s" % " ".join(repr(m) for m in missing))
    if "--preview" in sys.argv:
        preview()
    else:
        here = os.path.dirname(os.path.abspath(__file__))
        emit(os.path.join(here, "..", "src", "ui", "UiFont.cpp"))
